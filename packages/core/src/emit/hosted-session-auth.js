function publicOrigin(env) {
  if (env.AUTH_PUBLIC_ORIGIN) return env.AUTH_PUBLIC_ORIGIN;
  if (env.NODE_ENV !== 'production' && env.PORT) return 'http://127.0.0.1:' + Number(env.PORT);
  throw new Error('AUTH_PUBLIC_ORIGIN is required in production');
}

